/**
 * Generate `server/src/passage-text-parsers/chapbook/window-globals.ts`.
 *
 * Chapbook can't expose a story variable to JavaScript if a truthy global of
 * the same name already exists on `window`. This script launches Chromium,
 * Firefox, and WebKit (via Playwright), collects every truthy name on `window`
 * and its prototype chain, and writes them.
 *
 * Usage:
 *   npm run build-window-globals           Regenerate the list; commit the result.
 *   npm run build-window-globals -- --check  Exit non-zero if the committed list
 *                                          differs from a freshly-generated one.
 *
 * The pinned Playwright version pins the browser versions, so output is
 * deterministic. The file is rewritten only if the name set changes.
 *
 * The browsers must be installed first:
 *   npx playwright install --with-deps chromium firefox webkit
 */
import { readFile, writeFile } from "node:fs/promises";
import path from "node:path";
import { chromium, firefox, webkit, type BrowserType } from "playwright";

const outputPath = path.resolve(
    "server",
    "src",
    "passage-text-parsers",
    "chapbook",
    "window-globals.ts",
);

const browserTypes: [string, BrowserType][] = [
    ["Chromium", chromium],
    ["Firefox", firefox],
    ["WebKit", webkit],
];

const INSTALL_COMMAND =
    "npx playwright install --with-deps chromium firefox webkit";

/**
 * Collect the names of all truthy values on `window` and its prototype chain.
 *
 * Runs inside the browser, so it must be self-contained.
 */
function collectTruthyWindowNames(): string[] {
    const names = new Set<string>();
    const w = window as any;
    for (
        let obj: any = w;
        obj !== null && obj !== undefined;
        obj = Object.getPrototypeOf(obj)
    ) {
        for (const name of Object.getOwnPropertyNames(obj)) {
            try {
                if (w[name]) names.add(name);
            } catch {
                // Some getters throw; those aren't usable globals
            }
        }
    }
    return [...names];
}

async function collectGlobals(): Promise<{
    names: Set<string>;
    versions: [string, string][];
}> {
    const names = new Set<string>();
    const versions: [string, string][] = [];
    for (const [label, type] of browserTypes) {
        try {
            const browser = await type.launch();
            try {
                const page = await browser.newPage();
                await page.goto("about:blank");
                const found = await page.evaluate(
                    `(${collectTruthyWindowNames.toString()})()`,
                );
                for (const n of found as string[]) names.add(n);
                versions.push([label, browser.version()]);
            } finally {
                await browser.close();
            }
        } catch (e) {
            throw new Error(
                `Couldn't launch ${label}: ${(e as Error).message.split("\n")[0]}\n` +
                    `Install the browsers with: ${INSTALL_COMMAND}`,
            );
        }
    }
    return { names, versions };
}

function renderFile(names: Set<string>, versions: [string, string][]): string {
    const sorted = [...names].sort();
    return `/**
 * Truthy names on \`window\` in Chromium, Firefox, or WebKit.
 *
 * If an author has a story variable with one of these names, it won't be
 * available in a JavaScript context because Chapbook makes story vars available
 * via proxies on \`window\`, and it skips any pre-existing truthy name on
 * \`window\`, whoops.

 * This file is generated by \`scripts/build-window-globals.ts\`; do not edit.
 * Regenerate it with \`npm run build-window-globals\` (needs the browsers from
 * \`${INSTALL_COMMAND}\`)
 * and commit the result. \`npm run build-window-globals -- --check\` verifies it.
 *
 * This file built with the following browser versions:
${versions.map(([l, v]) => ` * ${l}: ${v}`).join("\n")}
 */
export const windowGlobals: ReadonlySet<string> = new Set([
${sorted.map((n) => `    ${JSON.stringify(n)},`).join("\n")}
]);
`;
}

function parseCommittedNames(contents: string): Set<string> {
    const body = contents.slice(contents.indexOf("new Set(["));
    return new Set(
        [...body.matchAll(/^\s+"((?:[^"\\]|\\.)*)",$/gm)].map((m) =>
            JSON.parse(`"${m[1]}"`),
        ),
    );
}

async function main(): Promise<void> {
    const check = process.argv.includes("--check");
    const { names, versions } = await collectGlobals();

    let existing: Set<string> | undefined;
    try {
        existing = parseCommittedNames(await readFile(outputPath, "utf8"));
    } catch {
        existing = undefined;
    }

    const added = [...names].filter((n) => !existing?.has(n)).sort();
    const removed = [...(existing ?? [])].filter((n) => !names.has(n)).sort();
    const same = existing !== undefined && !added.length && !removed.length;

    if (check) {
        if (same) {
            console.log("window-globals.ts is up to date.");
            return;
        }
        console.error("window-globals.ts is out of date.");
        if (added.length) console.error(`Added: ${added.join(", ")}`);
        if (removed.length) console.error(`Removed: ${removed.join(", ")}`);
        console.error("Run `npm run build-window-globals` and commit.");
        process.exitCode = 1;
        return;
    }

    if (same) {
        console.log("window-globals.ts unchanged.");
        return;
    }
    await writeFile(outputPath, renderFile(names, versions), "utf8");
    console.log(`Wrote ${names.size} names to ${outputPath}`);
}

main().catch((e) => {
    console.error(e.message);
    process.exitCode = 1;
});
